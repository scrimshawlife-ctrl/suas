/**
 * Embeds the vendored VA projection files as text in src/identity/va-projection-artifact.ts.
 *
 * contract/va-projection/ holds byte-identical copies of suas-specs
 * evidence/d035/va-confirmation-v1-required-only.{projection,approval}.json. To take a new
 * version, copy both files there unchanged and run `npm run va:projection`. The startup
 * check hashes the embedded projection text, so the module must match the files exactly;
 * tests/unit/va-projection-approval.test.ts fails when it does not.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VA_PROJECTION_DIR = path.join(ROOT, 'contract/va-projection');
const VA_PROJECTION_FILE = 'va-confirmation-v1-required-only.projection.json';
const VA_PROJECTION_APPROVAL_FILE = 'va-confirmation-v1-required-only.approval.json';
const TARGET = path.join(ROOT, 'src/identity/va-projection-artifact.ts');

const read = (name: string) => readFileSync(path.join(VA_PROJECTION_DIR, name), 'utf8');

const module = `/**
 * GENERATED by \`npm run va:projection\` from contract/va-projection/. Do not edit.
 *
 * The approved VA projection and its approval record (suas-specs VA_CONFIRMATION_FLOW §3),
 * as the exact file text. Embedded rather than read from disk so the startup hash covers
 * the same bytes in every build (tsx, dist, the Lambda bundle) with no file to ship.
 */

export const VA_PROJECTION_FILE_TEXT = ${JSON.stringify(read(VA_PROJECTION_FILE))};

export const VA_PROJECTION_APPROVAL_TEXT = ${JSON.stringify(read(VA_PROJECTION_APPROVAL_FILE))};
`;

writeFileSync(TARGET, module);
console.log(`wrote ${path.relative(ROOT, TARGET)}`);
